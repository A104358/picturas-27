const assert = require("node:assert/strict");
const { parser, JOIN_BYTES } = require("../../../wsGateway/protocol");
const decoder = new parser.Decoder();
const packets = [];
decoder.on("decoded", (packet) => packets.push(packet));
const payload = { projectId: "000000000000000000000001", access: { kind: "share", shareId: "é" } };
const value = JSON.stringify(payload);
decoder.add(`21["join-project",${value}]`);
assert.equal(packets[0].data[1][JOIN_BYTES], Buffer.byteLength(value));
assert.equal(JSON.stringify(packets[0].data[1]), value);
const escaped = value.replace("é", "\\u00e9");
decoder.add(`22["join\\u002dproject", ${escaped} ]`);
assert.equal(packets[1].data[1][JOIN_BYTES], Buffer.byteLength(escaped) + 2);
assert.equal(JSON.stringify(packets[1].data[1]), value);
const auth = JSON.stringify({ token: "fixture", padding: "" });
const exact = auth.replace('"padding":""', '"padding":"' + "x".repeat(8192 - Buffer.byteLength(auth)) + '"');
assert.equal(Buffer.byteLength(exact), 8192);
decoder.add("0" + exact);
assert.throws(() => decoder.add("0" + exact.replace("fixture", "fixturex")), /8 KiB/);
assert.throws(() => decoder.add('51-["unused",{"_placeholder":true,"num":0}]'), /JSON messages/);
assert.ok(!decoder.reconstructor);
console.log("PASS wire parser: exact handshake, +1, UTF-8 escapes/whitespace, no metadata serialization, no binary reconstruction queue");
